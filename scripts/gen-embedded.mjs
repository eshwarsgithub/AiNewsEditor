// Embeds the Telugu fonts and bundled sample photos as base64 in one TS module,
// so the renderer works on Cloudflare Workers (no file system there).
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const font = (pkg, file) => fs.readFileSync(path.join(root, "node_modules/@fontsource", pkg, "files", file)).toString("base64");
const face = (family, pkg, file, weight) =>
  `@font-face{font-family:"${family}";font-weight:${weight};font-style:normal;src:url(data:font/woff2;base64,${font(pkg, file)}) format("woff2");}`;

const css = [
  face("Anek Telugu", "anek-telugu", "anek-telugu-telugu-400-normal.woff2", 400),
  face("Anek Telugu", "anek-telugu", "anek-telugu-telugu-800-normal.woff2", 800),
  face("Anek Telugu Latin", "anek-telugu", "anek-telugu-latin-400-normal.woff2", 400),
  face("Anek Telugu Latin", "anek-telugu", "anek-telugu-latin-800-normal.woff2", 800),
  face("Noto Serif Telugu", "noto-serif-telugu", "noto-serif-telugu-telugu-400-normal.woff2", 400),
  face("Noto Serif Telugu", "noto-serif-telugu", "noto-serif-telugu-telugu-700-normal.woff2", 700),
  face("Noto Serif Telugu Latin", "noto-serif-telugu", "noto-serif-telugu-latin-400-normal.woff2", 400),
  face("Noto Serif Telugu Latin", "noto-serif-telugu", "noto-serif-telugu-latin-700-normal.woff2", 700),
].join("\n");

const imgDir = path.join(root, "samples/images");
const images = {};
for (const f of fs.readdirSync(imgDir).sort()) {
  images[`samples/images/${f}`] = `data:image/svg+xml;base64,${fs.readFileSync(path.join(imgDir, f)).toString("base64")}`;
}

const out = `// GENERATED by scripts/gen-embedded.mjs. Do not edit.\nexport const FONT_CSS = ${JSON.stringify(css)};\nexport const SAMPLE_IMAGES: Record<string, string> = ${JSON.stringify(images)};\n`;
fs.writeFileSync(path.join(root, "lib/render/embedded.generated.ts"), out);
console.log("embedded.generated.ts", (out.length / 1024).toFixed(0), "KB");
